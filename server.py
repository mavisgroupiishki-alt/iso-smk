def _is_labour_book_filename(filename: str) -> bool:
    """Return True for labour-book scans and inserts.

    Long labour books are the main source for experience calculation, so they must
    not be silently truncated to the first few pages.
    """
    name = str(filename or '').lower().replace('ё', 'е')
    return any(marker in name for marker in (
        'трудов', 'вкладыш', 'trudov', 'vkladysh', 'labour', 'labor', 'workbook',
    ))


def _pdf_page_limit(filename: str) -> int:
    """Use a larger safe page limit for labour books than for ordinary PDFs."""
    return 24 if _is_labour_book_filename(filename) else 6


